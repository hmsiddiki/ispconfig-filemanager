#!/usr/bin/env bash
#
# Builds release/ispconfig-filemanager-<version>.tar.gz (+ .sha256): everything needed to install the file manager on an
# ISPConfig server, with no Node, Composer or internet needed there.
#
# Run from the repository root after:
#     npm ci --ignore-scripts && NODE_OPTIONS=--openssl-legacy-provider npm run build      (front end  -> dist/)
#     composer install --no-dev --optimize-autoloader                                       (PHP libs   -> vendor/)
#
#   ./scripts/build-package.sh
#
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VERSION="$(tr -d '[:space:]' < "$ROOT/VERSION")"
NAME="ispconfig-filemanager-$VERSION"
OUT="$ROOT/release"
STAGE="$OUT/$NAME"

[[ "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+([.-][0-9A-Za-z.]+)?$ ]] || { echo "VERSION file must look like 1.2.3 (got '$VERSION')" >&2; exit 1; }
[ -d "$ROOT/backend" ] && [ -d "$ROOT/vendor" ] || { echo "backend/ or vendor/ missing: run 'composer install --no-dev' first" >&2; exit 1; }
[ -f "$ROOT/dist/js/app.js" ] || { echo "front end not built: run 'npm run build' first" >&2; exit 1; }
[ -f "$ROOT/vendor/phpseclib/phpseclib/composer.json" ] || { echo "vendor/ looks incomplete (phpseclib missing)" >&2; exit 1; }
[ ! -d "$ROOT/vendor/phpunit" ] || { echo "vendor/ contains dev packages: run 'composer install --no-dev --optimize-autoloader'" >&2; exit 1; }

rm -rf "$STAGE"
mkdir -p "$STAGE/payload/web"

# the program and its libraries (no tests, docs or dev tools)
cp -a "$ROOT/backend" "$STAGE/payload/backend"
cp -a "$ROOT/vendor" "$STAGE/payload/vendor"
find "$STAGE/payload/vendor" -type d \( -iname tests -o -iname test -o -iname docs -o -iname examples -o -iname .github \) -prune -exec rm -rf {} +
find "$STAGE/payload/vendor" -type f \( -iname "*.md" -o -iname "phpunit*" -o -iname ".gitignore" -o -iname ".editorconfig" \) -delete

# the built front end (no source maps) plus the static files; index.php is generated by the installer
cp -a "$ROOT/dist/." "$STAGE/payload/web/"
find "$STAGE/payload/web" -name "*.map" -delete
cp -a "$ROOT/static/." "$STAGE/payload/web/"
rm -f "$STAGE/payload/web/index.php"

# installer, templates, tools, documents
cp -a "$ROOT/installer/." "$STAGE/"
cp "$ROOT/README.md" "$ROOT/LICENSE" "$ROOT/NOTICE" "$ROOT/CHANGELOG.md" "$STAGE/"
echo "$VERSION" > "$STAGE/VERSION"
chmod +x "$STAGE/install.sh" "$STAGE/uninstall.sh"

# the scripts are run by bash on Linux: Windows line endings would break them
find "$STAGE" -type f \( -name "*.sh" -o -name "*.php" -o -name "*.tpl" -o -name "*.md" -o -name "*.js" \) -not -path "*/payload/vendor/*" -not -path "*/payload/web/*" -exec sed -i 's/\r$//' {} +

( cd "$OUT" && tar -czf "$NAME.tar.gz" "$NAME" )
( cd "$OUT" && sha256sum "$NAME.tar.gz" > "$NAME.tar.gz.sha256" )

echo "built: $OUT/$NAME.tar.gz ($(du -h "$OUT/$NAME.tar.gz" | cut -f1))"
echo "sha256: $(cut -d' ' -f1 "$OUT/$NAME.tar.gz.sha256")"
